"""Generate the lane's SM75 dispatch header from the fixed sweep selection.
Usage: python gen_prefetch.py extra-tune-selection.csv > inkling_prefetch_select.cuh
"""
import csv,sys,itertools,collections
choices=collections.defaultdict(dict)
for r in csv.DictReader(open(sys.argv[1])):
 c,n,k,b=map(int,[r['codec'],r['n'],r['k'],r['m_bin']]);assert float(r['test_max_ratio'])<=1
 if r['tile']!='deployed':choices[c,n,k][b]=r['tile']
print('''// Generated by engine/tools/inkling-prefill-weight-gemm/gen_prefetch.py.
// True means a kernel was enqueued: caller checks its launch status exactly once.
inline bool inkling_prefetch_select(const inference_cuda_dense_gemv_args &a,int codec,cudaStream_t s,int *measure_bm=nullptr){
    if(!aligned(a.x,16) || a.ld_x%4 || !(a.m==7 || a.m==8 || a.m==12 || a.m==63 || a.m==64))return false;
    const int bin=a.m<=8?0:a.m==12?1:2;
#define CHOOSE(C,M,R,K) {if(measure_bm){*measure_bm=M;return true;}inkling_prefetch<C,M,R,K,true><<<dim3(a.rows/(8*R),(a.m+M-1)/M),256,0,s>>>(a);return true;}
    switch(codec){''')
for c,g in itertools.groupby(sorted(choices),key=lambda key:key[0]):
 print(f'    case {c}:');
 for key in g:
  _,n,k=key;print(f'        if(a.rows=={n} && a.cols=={k})'+'{');b=collections.defaultdict(list)
  for idx,tile in choices[key].items():b[tile].append(idx)
  for tile,bins in b.items():
   m,r,bk,_=tile.split(':');cond=' || '.join(f'bin=={i}' for i in bins);print(f'            if({cond}) CHOOSE({c},{m},{r},{bk})')
  print('        }');
 print('        break;');
print('''    }
#undef CHOOSE
    return false;
}''')
